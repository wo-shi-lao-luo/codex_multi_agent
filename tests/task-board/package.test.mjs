/** P4 builder contract on disposable source copies; final feature payload is a separate checkpoint. */
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdir, mkdtemp, cp, readFile, writeFile, readdir, rm, symlink } from 'node:fs/promises';
import { resolve, join, dirname } from 'node:path';
import { createHash } from 'node:crypto';

const root = resolve('.');
const runtimePath = 'skills/team-core/runtime/task-board';

/** Copy only the frozen builder inputs into an owned fixture and remove only that fixture. */
async function fixture(t) {
  const parent = resolve('_work/task-board/test-fixtures');
  await mkdir(parent, { recursive: true });
  const directory = await mkdtemp(join(parent, 'p4-builder-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  for (const path of ['packages/task-board', 'scripts/build-task-board.mjs',
    '.gitattributes', 'VERSION']) {
    await mkdir(join(directory, path, '..'), { recursive: true });
    await cp(join(root, path), join(directory, path), { recursive: true });
  }
  return directory;
}

/** Run the real copied builder with the pinned current process runtime; no package downloads. */
function build(directory, check = false) {
  return spawnSync(process.execPath, [join(directory, 'scripts/build-task-board.mjs'),
    '--project-root', directory, ...(check ? ['--check'] : [])], { encoding: 'utf8' });
}

/** Independently hash every generated file, including manifest, to detect nondeterministic bytes. */
async function fingerprint(directory) {
  const entries = {};
  async function walk(path, prefix = '') {
    for (const item of await readdir(path, { withFileTypes: true })) {
      const name = `${prefix}${item.name}`;
      if (item.isDirectory()) await walk(join(path, item.name), `${name}/`);
      else entries[name] = createHash('sha256').update(await readFile(join(path, item.name)))
        .digest('hex');
    }
  }
  await walk(directory);
  return entries;
}

// Scenario: two builds of identical LF sources followed by read-only check.
// Expected: all generated bytes, including manifest, are identical and exact inventories validate.
test('P4.builderDeterministic', async t => {
  const directory = await fixture(t);
  const first = build(directory);
  assert.equal(first.status, 0, first.stderr);
  const before = await fingerprint(join(directory, runtimePath));
  const second = build(directory);
  assert.equal(second.status, 0, second.stderr);
  assert.deepEqual(await fingerprint(join(directory, runtimePath)), before);
  const check = build(directory, true);
  assert.equal(check.status, 0, check.stderr);
  const manifest = JSON.parse(await readFile(join(directory, runtimePath, 'manifest.json')));
  assert.equal(manifest.schemaVersion, 1);
  assert.equal(manifest.licenseStatus, 'not-declared');
  for (const key of ['inputs', 'outputs']) {
    const paths = manifest[key].map(item => item.path);
    assert.deepEqual(paths, [...paths].sort());
    assert.equal(new Set(paths).size, paths.length);
    assert.ok(paths.every(path => !path.startsWith('/') && !path.includes('..')));
  }
  assert.ok(manifest.inputs.some(item => item.path === '.gitattributes'));
});

// Scenario: independently mutate bound input/output bytes, remove output, or add unexpected output.
// Expected: --check rejects each exact-set/hash violation with a TASK_BOARD diagnostic.
for (const mutation of ['input', 'output', 'missing', 'extra', 'unsafe', 'case-collision', 'link']) {
  test(`P4.builderCheck.${mutation}`, async t => {
    const directory = await fixture(t);
    const initial = build(directory);
    assert.equal(initial.status, 0, initial.stderr);
    const runtime = join(directory, runtimePath);
    if (mutation === 'input') {
      await writeFile(join(directory, 'packages/task-board/web/style.css'), '/* changed */\n');
    } else if (mutation === 'output') {
      await writeFile(join(runtime, 'web/style.css'), '/* changed */\n');
    } else if (mutation === 'missing') {
      await rm(join(runtime, 'web/style.css'));
    } else if (mutation === 'extra') {
      await writeFile(join(runtime, 'unexpected.txt'), 'not inventoried\n');
    } else if (mutation === 'link') {
      await symlink(join(directory, 'packages/task-board/web'),
        join(runtime, 'linked-web'), process.platform === 'win32' ? 'junction' : 'dir');
    } else {
      const path = join(runtime, 'manifest.json');
      const manifest = JSON.parse(await readFile(path));
      if (mutation === 'case-collision') {
        manifest.outputs.push({ ...manifest.outputs[0],
          path: manifest.outputs[0].path.toUpperCase() });
      } else manifest.outputs[0].path = '../outside';
      await writeFile(path, JSON.stringify(manifest));
    }
    const result = build(directory, true);
    assert.notEqual(result.status, 0);
    assert.match(result.stderr + result.stdout, /TASK_BOARD/);
  });
}

// Scenario: source contains a residual CRLF controlled text file instead of the required LF bytes.
// Expected: builder rejects explicitly rather than silently normalizing manifest-bound inputs.
test('P4.builderRejectsCRLF', async t => {
  const directory = await fixture(t);
  await writeFile(join(directory, 'packages/task-board/web/style.css'), 'body {}\r\n');
  const result = build(directory);
  assert.notEqual(result.status, 0);
  assert.match(result.stderr + result.stdout, /TASK_BOARD/);
});

// Scenario: a source license exists, then the generated runtime is copied without root packages.
// Expected: license bytes/hash are bound and the copied CLI initializes an owned actual SQLite board.
test('P4.licenseAndIsolatedRuntime', async t => {
  const directory = await fixture(t);
  await writeFile(join(directory, 'LICENSE'), 'Synthetic fixture license\n');
  const result = build(directory);
  assert.equal(result.status, 0, result.stderr);
  const runtime = join(directory, runtimePath);
  const manifest = JSON.parse(await readFile(join(runtime, 'manifest.json')));
  assert.equal(manifest.licenseStatus, 'present-unreviewed');
  assert.ok(manifest.inputs.some(item => item.path === 'LICENSE'));
  assert.ok(manifest.outputs.some(item => item.path === 'LICENSE'));
  assert.equal(await readFile(join(runtime, 'LICENSE'), 'utf8'), 'Synthetic fixture license\n');
  const installed = join(directory, 'installed-runtime');
  await cp(runtime, installed, { recursive: true });
  await rm(join(directory, 'packages'), { recursive: true });
  const project = join(directory, 'owned-project');
  await mkdir(join(project, 'src'), { recursive: true });
  const initialize = spawnSync(process.execPath, [join(installed, 'cli.mjs'), 'initialize',
    '--project-root', project, '--board-path', join(project, '_work/board'), '--stdin'], {
    encoding: 'utf8', input: JSON.stringify({ actorId: 'lead', leadToken: 'a'.repeat(64) }),
    // This genuine NoGit fixture must not discover the enclosing development repository.
    env: { ...process.env, GIT_CEILING_DIRECTORIES: dirname(project) },
  });
  assert.equal(initialize.status, 0, initialize.stderr + initialize.stdout);
  assert.equal(JSON.parse(initialize.stdout).ok, true);
});
