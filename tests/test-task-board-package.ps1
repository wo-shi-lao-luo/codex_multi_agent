# P4 trusted-deployer regression using owned fake package bytes and homes only.
# This fixture proves preview validation, not final feature payload or real installation readiness.
#requires -Version 7.0
[CmdletBinding()]
param(
  [ValidateSet('', 'outputs', 'license')][string]$ReviewCase = '',
  [switch]$CurrentPayload,
  [string]$NodePath,
  [string]$ExpectedManifestSha256,
  [string]$ExpectedAppSha256
)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'helpers/package-test.ps1')
$repo = Split-Path -Parent $PSScriptRoot
$manager = Join-Path $repo 'scripts/deploy-user.ps1'
$runtimeRelative = 'skills/team-core/runtime/task-board'
# Current real payloads require independently approved candidate hashes, before creating any fake homes.
# Fake ReviewCase packages retain their own generated inventory and do not require candidate approval.
if ($CurrentPayload) {
  if ($ExpectedManifestSha256 -notmatch '^[0-9a-fA-F]{64}$' -or
      $ExpectedAppSha256 -notmatch '^[0-9a-fA-F]{64}$') {
    throw 'CANDIDATE_HASH_REQUIRED: CurrentPayload requires both explicit 64-hex expected hashes.'
  }
  $currentRuntime = Join-Path $repo $runtimeRelative
  $manifestHash = (Get-FileHash -LiteralPath (Join-Path $currentRuntime 'manifest.json') -Algorithm SHA256).Hash
  $appHash = (Get-FileHash -LiteralPath (Join-Path $currentRuntime 'web/app.js') -Algorithm SHA256).Hash
  if ($manifestHash -ine $ExpectedManifestSha256 -or $appHash -ine $ExpectedAppSha256) {
    throw 'CANDIDATE_HASH_MISMATCH: Current payload differs from caller-approved frozen hashes.'
  }
}
$fixtureParent = Join-Path $repo '_work/task-board/test-fixtures'
New-Item -ItemType Directory -Path $fixtureParent -Force | Out-Null
$fixture = Join-Path $fixtureParent ('p4-package-' + [Guid]::NewGuid().ToString('N'))
$source = Join-Path $fixture 'source'
$runtime = Join-Path $source $runtimeRelative
$marker = Join-Path $fixture 'selected-build-ran'
$codex = Join-Path $fixture 'fake-codex'
$agents = Join-Path $fixture 'fake-agents'

# Write literal fixture content after creating its parent; no selected source is executed.
function Write-FixtureFile([string]$Relative, [string]$Content) {
  $path = Join-Path $source $Relative
  New-Item -ItemType Directory -Path (Split-Path -Parent $path) -Force | Out-Null
  [IO.File]::WriteAllText($path, $Content, [Text.UTF8Encoding]::new($false))
}

# Return the frozen manifest's root-relative path/hash inventory in ordinal path order.
function Get-Inventory([string[]]$Paths, [string]$Root) {
  $sorted = [string[]]$Paths.Clone()
  [Array]::Sort($sorted, [StringComparer]::Ordinal)
  return @($sorted | ForEach-Object {
    @{ path = $_; sha256 = (Get-FileHash -LiteralPath (Join-Path $Root $_) -Algorithm SHA256).Hash.ToLowerInvariant() }
  })
}

# Invoke the current trusted manager on an owned package; -WhatIf must leave homes absent.
function Invoke-Preview {
  return Invoke-TestProcess -FilePath (Get-Process -Id $PID).Path -ArgumentList @(
    '-NoProfile', '-File', $manager, '-Action', 'Deploy', '-SourceRoot', $source,
    '-CodexHome', $codex, '-AgentsHome', $agents, '-WhatIf'
  )
}

try {
  if ($CurrentPayload) {
    # Scenario: install the actual current prebuilt package only into owned fake homes.
    # Expected: trusted deployment validates/copies exact generated bytes and receipt verification
    # succeeds; installed wrapper runs real NoGit CLI independently of root source packages.
    New-Item -ItemType Directory -Path $fixture -Force | Out-Null
    $shell = (Get-Process -Id $PID).Path
    $deploy = Invoke-TestProcess -FilePath $shell -ArgumentList @(
      '-NoProfile', '-File', $manager, '-Action', 'Deploy', '-SourceRoot', $repo,
      '-CodexHome', $codex, '-AgentsHome', $agents
    )
    if ($deploy.Exit -ne 0) { throw "Current payload deploy failed: $($deploy.Error)" }
    $verified = Invoke-TestProcess -FilePath $shell -ArgumentList @(
      '-NoProfile', '-File', $manager, '-Action', 'Verify',
      '-CodexHome', $codex, '-AgentsHome', $agents
    )
    if ($verified.Exit -ne 0) { throw "Current receipt verification failed: $($verified.Error)" }
    $installedRuntime = Join-Path $agents 'skills/team-core/runtime/task-board'
    if ((Get-TestFingerprint $installedRuntime) -cne (Get-TestFingerprint $currentRuntime)) {
      throw 'Current installed runtime bytes differ from approved generated payload.'
    }
    $selectedNode = if ($NodePath) { $NodePath } else { 'node' }
    $nodeCommand = Get-Command $selectedNode -CommandType Application -ErrorAction SilentlyContinue |
      Select-Object -First 1
    if (-not $nodeCommand) { throw 'TEST_SETUP: NODE_MISSING; select -NodePath explicitly.' }
    $node = $nodeCommand.Source
    $installedCLI = Join-Path $installedRuntime 'cli.mjs'
    $help = Invoke-TestProcess -FilePath $node -ArgumentList @($installedCLI, 'help')
    if ($help.Exit -ne 0 -or ($help.Out | ConvertFrom-Json).ok -ne $true) {
      throw "Installed help failed: $($help.Error)"
    }
    $project = Join-Path $fixture 'owned-nogit-project'
    $projectBoard = Join-Path $project '_work/board'
    New-Item -ItemType Directory -Path "$project/src" -Force | Out-Null
    $token = [Convert]::ToHexString([Security.Cryptography.RandomNumberGenerator]::GetBytes(32)).ToLowerInvariant()
    # Run the installed CLI with private input files; require success/redaction and return parsed JSON.
    # Private request files stay inside the owned temporary fixture and are deleted in finally.
    function Invoke-InstalledCLI([string]$Operation, [hashtable]$Payload) {
      $requestPath = Join-Path $fixture ("private-$Operation.json")
      [IO.File]::WriteAllText($requestPath, ($Payload | ConvertTo-Json -Depth 12), [Text.UTF8Encoding]::new($false))
      $response = Invoke-TestProcess -FilePath $node -ArgumentList @(
        $installedCLI, $Operation, '--project-root', $project, '--board-path', $projectBoard,
        '--input', $requestPath
      ) -Environment @{ GIT_CEILING_DIRECTORIES = [IO.Path]::GetDirectoryName($project) }
      if ($response.Exit -ne 0) { throw "Installed $Operation failed: $($response.Error) $($response.Out)" }
      $reply = $response.Out | ConvertFrom-Json
      if ($reply.ok -ne $true -or $response.Out.Contains($token)) { throw 'Installed CLI failed or exposed credential.' }
      return $reply
    }
    $initialized = Invoke-InstalledCLI 'initialize' @{ actorId = 'lead'; leadToken = $token }
    $null = Invoke-InstalledCLI 'add' @{ actorId = 'lead'; leadToken = $token;
      generation = $initialized.generation; operationId = 'current-package-add'; task = @{
        id = 'installed-smoke'; title = 'Installed runtime smoke'; outcome = 'Actual isolated CLI';
        sourceRefs = @('fixture/source#installed'); acceptanceRefs = @('fixture/accept#installed');
        eligibleRoles = @('backend'); scope = @{ read = @(); write = @('src/output.mjs') };
        resources = @(); dependencies = @() } }
    $status = Invoke-InstalledCLI 'status' @{ actorId = 'lead'; leadToken = $token;
      generation = $initialized.generation }
    if (@($status.result.tasks | Where-Object id -eq 'installed-smoke').Count -ne 1) {
      throw 'Installed CLI status omitted actual added task.'
    }
    $database = Join-Path $projectBoard 'board.sqlite'
    $databaseHash = (Get-FileHash -LiteralPath $database -Algorithm SHA256).Hash
    $sentinel = Join-Path $project 'project-db-sentinel.sqlite'
    [IO.File]::WriteAllBytes($sentinel, [byte[]](0, 1, 2, 3, 255))
    $sentinelHash = (Get-FileHash -LiteralPath $sentinel -Algorithm SHA256).Hash
    Write-Output "PASS P4.currentPayloadInstalledAndCLI manifest=$manifestHash app=$appHash"

    # Scenario: legacy downgrade replaces the installed full Kit while project database is external.
    # Expected: no new runtime remains, receipt verifies and real project DB plus sentinel unchanged.
    $legacy = Join-Path $fixture 'current-payload-legacy'
    New-Item -ItemType Directory -Path "$legacy/agents", "$legacy/skills/team-core" -Force | Out-Null
    [IO.File]::WriteAllText("$legacy/VERSION", '0.1.0')
    [IO.File]::WriteAllText("$legacy/agents/team-fixture.toml", 'name = "team-fixture"')
    [IO.File]::WriteAllText("$legacy/skills/team-core/SKILL.md", "---`nname: team-core`ndescription: Legacy fixture.`n---")
    $rollback = Invoke-TestProcess -FilePath $shell -ArgumentList @(
      '-NoProfile', '-File', $manager, '-Action', 'Deploy', '-SourceRoot', $legacy,
      '-CodexHome', $codex, '-AgentsHome', $agents
    )
    if ($rollback.Exit -ne 0) { throw "Current payload legacy rollback failed: $($rollback.Error)" }
    if (Test-Path -LiteralPath $installedRuntime) { throw 'Current runtime remains after legacy rollback.' }
    $verifiedLegacy = Invoke-TestProcess -FilePath $shell -ArgumentList @(
      '-NoProfile', '-File', $manager, '-Action', 'Verify',
      '-CodexHome', $codex, '-AgentsHome', $agents
    )
    if ($verifiedLegacy.Exit -ne 0) { throw "Legacy receipt verification failed: $($verifiedLegacy.Error)" }
    if ((Get-FileHash -LiteralPath $database -Algorithm SHA256).Hash -cne $databaseHash -or
        (Get-FileHash -LiteralPath $sentinel -Algorithm SHA256).Hash -cne $sentinelHash) {
      throw 'Current package rollback changed project database or sentinel bytes.'
    }
    $legacyReceipt = Get-Content -LiteralPath (Join-Path $agents 'codex-multi-agent/install-receipt.json') -Raw | ConvertFrom-Json
    if ($legacyReceipt.kitVersion -ne '0.1.0') { throw 'Legacy receipt version mismatch.' }
    Write-Output 'PASS P4.currentPayloadLegacyRollbackNoRuntimeAndProjectDatabasePreserved'
    return
  }
  Write-FixtureFile 'VERSION' '1.0.0'
  Write-FixtureFile '.gitattributes' ([IO.File]::ReadAllText((Join-Path $repo '.gitattributes')))
  Write-FixtureFile 'LICENSE' "Owned synthetic fixture license`n"
  Write-FixtureFile 'agents/team-fixture.toml' 'name = "team-fixture"'
  Write-FixtureFile 'skills/team-core/SKILL.md' "---`nname: team-core`ndescription: Owned fixture.`n---"
  Write-FixtureFile 'packages/task-board/package.json' '{"name":"fixture-task-board","type":"module"}'
  Write-FixtureFile 'packages/task-board/src/cli/cli.mjs' 'console.log("fixture only");'
  Write-FixtureFile 'packages/task-board/web/index.html' '<!doctype html><title>Fixture</title>'
  $markerLiteral = ConvertTo-Json -InputObject $marker -Compress
  Write-FixtureFile 'scripts/build-task-board.mjs' "import {writeFileSync} from 'node:fs'; writeFileSync($markerLiteral,'executed');"
  Write-FixtureFile "$runtimeRelative/cli.mjs" "// Generated by build-task-board; do not edit.`nimport './src/cli/cli.mjs';`n"
  foreach ($relative in @('package.json', 'src/cli/cli.mjs', 'web/index.html')) {
    $inputPath = Join-Path $source "packages/task-board/$relative"
    Write-FixtureFile "$runtimeRelative/$relative" ([IO.File]::ReadAllText($inputPath))
  }
  Write-FixtureFile "$runtimeRelative/LICENSE" "Owned synthetic fixture license`n"
  $inputs = @('.gitattributes', 'VERSION', 'LICENSE', 'scripts/build-task-board.mjs',
    'packages/task-board/package.json', 'packages/task-board/src/cli/cli.mjs',
    'packages/task-board/web/index.html')
  $outputs = @('cli.mjs', 'LICENSE', 'package.json', 'src/cli/cli.mjs', 'web/index.html')
  $manifest = @{
    schemaVersion = 1
    licenseStatus = 'present-unreviewed'
    inputs = @(Get-Inventory $inputs $source)
    outputs = @(Get-Inventory $outputs $runtime)
    buildTool = @{ name = 'build-task-board'; version = 1 }
    requiredNode = '>=26.13.0 <27'
    minimumSQLite = '3.54.0'
    dependencyLock = 'none;standard-library-only'
    platformValidation = @{ observed = @('win32-x64'); otherPlatforms = 'unverified' }
  }
  Write-FixtureFile "$runtimeRelative/manifest.json" ($manifest | ConvertTo-Json -Depth 10)

  # Scenario: preview a valid prebuilt package containing an executable selected build marker.
  # Expected: preview succeeds without executing that build or creating either fake home.
  $baseline = Invoke-Preview
  if ($baseline.Exit -ne 0) { throw "Valid preview failed: $($baseline.Error) $($baseline.Out)" }
  if ((Test-Path -LiteralPath $marker) -or (Test-Path -LiteralPath $codex) -or
      (Test-Path -LiteralPath $agents)) { throw 'Preview executed selected build or changed homes.' }
  Write-Output 'PASS P4.previewNoBuild baseline (preview only, no install/E2E claim)'

  if ($ReviewCase -ne 'license') {
    $reviewFailures = [Collections.Generic.List[string]]::new()
    # Scenario: a generated wrapper or copied license is changed and its manifest hash recomputed.
    # Expected: trusted verifier rejects semantic source/output mismatch, not trusting self-rehashed
    # metadata; root source bytes, marker absence and fake-home absence must remain unchanged.
    foreach ($output in @('cli.mjs', 'LICENSE')) {
      $path = Join-Path $runtime $output
      $originalBytes = [IO.File]::ReadAllBytes($path)
      $sourceLicense = [IO.File]::ReadAllBytes((Join-Path $source 'LICENSE'))
      $manifestPath = Join-Path $runtime 'manifest.json'
      $originalManifest = [IO.File]::ReadAllBytes($manifestPath)
      try {
        [IO.File]::WriteAllText($path, "changed generated $output`n", [Text.UTF8Encoding]::new($false))
        $changed = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
        ($changed.outputs | Where-Object path -CEQ $output).sha256 =
          (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
        [IO.File]::WriteAllText($manifestPath, ($changed | ConvertTo-Json -Depth 10),
          [Text.UTF8Encoding]::new($false))
        $result = Invoke-Preview
        if ($result.Exit -eq 0) {
          Write-Output "RED P4.rejectRehashed.$output unsafe preview accepted recomputed output hash"
          $reviewFailures.Add($output)
        } elseif (($result.Error + $result.Out) -notmatch 'TASK_BOARD') {
          throw "Unexpected rejection category: $($result.Error) $($result.Out)"
        } else { Write-Output "PASS P4.rejectRehashed.$output" }
        if ([Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $source 'LICENSE'))) -cne
            [Convert]::ToBase64String($sourceLicense)) { throw 'Root source license changed.' }
        if ((Test-Path -LiteralPath $marker) -or (Test-Path -LiteralPath $codex) -or
            (Test-Path -LiteralPath $agents)) { throw 'Rehashed preview executed code or changed homes.' }
      } finally {
        [IO.File]::WriteAllBytes($path, $originalBytes)
        [IO.File]::WriteAllBytes($manifestPath, $originalManifest)
      }
    }
    if ($reviewFailures.Count -gt 0) {
      throw "P4 rehashed generated output accepted: $($reviewFailures -join ', '); expected TASK_BOARD rejection."
    }
    if ($ReviewCase -eq 'outputs') { return }
  }
  # Scenario: payload bytes differ from the committed manifest while source remains unchanged.
  # Expected: trusted current manager rejects with TASK_BOARD before previewing any installation;
  # no selected build runs and neither fake home is created.
  Add-Content -LiteralPath (Join-Path $runtime 'web/index.html') -Value '<!-- tampered -->'
  $tampered = Invoke-Preview
  if ((Test-Path -LiteralPath $marker) -or (Test-Path -LiteralPath $codex) -or
      (Test-Path -LiteralPath $agents)) { throw 'Tampered preview executed build or changed homes.' }
  if ($tampered.Exit -eq 0) {
    throw 'P4.rejectTamperedPayload: unsafe preview accepted manifest-mismatched output; expected TASK_BOARD rejection.'
  }
  if (($tampered.Error + $tampered.Out) -notmatch 'TASK_BOARD') {
    throw "Wrong failure category: $($tampered.Error) $($tampered.Out)"
  }
  Write-Output 'PASS P4.rejectTamperedPayload'
  # Scenario: new source exists without the generated runtime, while fake homes are still absent.
  # Expected: partial feature is rejected before any home state is processed, not treated as legacy.
  $hiddenRuntime = Join-Path $fixture 'hidden-runtime'
  Move-Item -LiteralPath $runtime -Destination $hiddenRuntime
  try {
    $partial = Invoke-Preview
    if ($partial.Exit -eq 0 -or ($partial.Error + $partial.Out) -notmatch 'TASK_BOARD') {
      throw 'Partial source-only feature must be rejected with TASK_BOARD.'
    }
    if ((Test-Path -LiteralPath $codex) -or (Test-Path -LiteralPath $agents)) {
      throw 'Partial validation touched fake homes.'
    }
  } finally { Move-Item -LiteralPath $hiddenRuntime -Destination $runtime }
  Write-Output 'PASS P4.rejectPartialFeature'
  # Scenario: an exact local Git ref is committed and checked out with autocrlf enabled.
  # Expected: LF-pinned manifest bytes survive checkout/archive and trusted offline install;
  # selected build is not executed, no Node is required for copy/verification, and receipt binds ref.
  [IO.File]::WriteAllText((Join-Path $runtime 'web/index.html'),
    [IO.File]::ReadAllText((Join-Path $source 'packages/task-board/web/index.html')),
    [Text.UTF8Encoding]::new($false))
  $git = (Get-Command git -CommandType Application | Select-Object -First 1).Source
  $emptyHooks = Join-Path $fixture 'empty-hooks'
  New-Item -ItemType Directory -Path $emptyHooks | Out-Null
  function Invoke-FixtureGit([string[]]$GitArguments) {
    $result = Invoke-TestProcess -FilePath $git -ArgumentList $GitArguments
    if ($result.Exit -ne 0) { throw "Fixture git failed: $($result.Error)" }
    return $result.Out.Trim()
  }
  $null = Invoke-FixtureGit @('init', '--quiet', "--template=$emptyHooks", $source)
  $null = Invoke-FixtureGit @('-C', $source, 'config', 'core.autocrlf', 'true')
  $null = Invoke-FixtureGit @('-C', $source, 'add', '.')
  $null = Invoke-FixtureGit @('-C', $source, '-c', 'user.name=Fixture', '-c',
    'user.email=fixture@example.invalid', '-c', 'commit.gpgsign=false', '-c',
    "core.hooksPath=$emptyHooks", 'commit', '--quiet', '-m', 'owned fixture only')
  $commit = Invoke-FixtureGit @('-C', $source, 'rev-parse', 'HEAD')
  $checkout = Join-Path $fixture 'checkout'
  New-Item -ItemType Directory -Path $checkout | Out-Null
  # Explicit work-tree checkout avoids Git local-clone shell transport in the sandbox.
  $null = Invoke-FixtureGit @('-C', $source, "--work-tree=$checkout", '-c',
    'core.autocrlf=true', '-c', "core.hooksPath=$emptyHooks", 'checkout', '--force', $commit, '--', '.')
  $archive = Join-Path $fixture 'archive.zip'
  $null = Invoke-FixtureGit @('-C', $source, 'archive', '--format=zip', "--output=$archive", $commit)
  $unpacked = Join-Path $fixture 'unpacked'
  Expand-Archive -LiteralPath $archive -DestinationPath $unpacked
  foreach ($selected in @($checkout, $unpacked)) {
    $verified = Invoke-TestProcess -FilePath (Get-Process -Id $PID).Path -ArgumentList @(
      '-NoProfile', '-File', $manager, '-Action', 'ValidateTaskBoard', '-SourceRoot', $selected
    )
        if ($verified.Exit -ne 0) {
      $selectedManifest = Get-Content -LiteralPath (Join-Path $selected "$runtimeRelative/manifest.json") -Raw | ConvertFrom-Json
      $changedInputs = @($selectedManifest.inputs | Where-Object {
        (Get-FileHash -LiteralPath (Join-Path $selected $_.path) -Algorithm SHA256).Hash.ToLowerInvariant() -cne $_.sha256
      } | ForEach-Object path)
      throw "Git checkout/archive changed bound inputs [$($changedInputs -join ', ')] at $([IO.Path]::GetFileName($selected)): $($verified.Error)"
    }
  }
  $project = Join-Path $fixture 'separate-project'
  New-Item -ItemType Directory -Path $project | Out-Null
  $database = Join-Path $project 'board.sqlite'
  [IO.File]::WriteAllBytes($database, [byte[]](0, 1, 2, 3, 255))
  $databaseHash = (Get-FileHash -LiteralPath $database).Hash
  $minimalPath = @((Split-Path -Parent $git), (Join-Path $env:SystemRoot 'System32')) -join [IO.Path]::PathSeparator
  $deploy = Invoke-TestProcess -FilePath (Get-Process -Id $PID).Path -ArgumentList @(
    '-NoProfile', '-File', $manager, '-Action', 'Deploy', '-SourceRoot', $source,
    '-GitRef', $commit, '-CodexHome', $codex, '-AgentsHome', $agents
  ) -Environment @{ PATH = $minimalPath }
  if ($deploy.Exit -ne 0) { throw "Exact-ref install failed: $($deploy.Error)" }
  if (Test-Path -LiteralPath $marker) { throw 'Install executed selected build.' }
  $receiptPath = Join-Path $agents 'codex-multi-agent/install-receipt.json'
  $receipt = Get-Content -LiteralPath $receiptPath -Raw | ConvertFrom-Json
  if ($receipt.source.commit -cne $commit) { throw 'Receipt does not bind selected commit.' }
  $installedManager = Join-Path $agents 'codex-multi-agent/manager/deploy-user.ps1'
  if (-not (Test-Path -LiteralPath $installedManager)) {
    # The persistent launcher location is owned by the established deployment contract.
    $installedManager = Join-Path $agents 'codex-multi-agent/manager/current/deploy-user.ps1'
  }
  $managerCandidates = @(Get-ChildItem -LiteralPath (Join-Path $agents 'codex-multi-agent') -Recurse -File -Filter 'deploy-user.ps1')
  if ($managerCandidates.Count -ne 1) { throw 'Expected one self-contained trusted persistent manager.' }
  $installedManager = $managerCandidates[0].FullName
  $persistentVerify = Invoke-TestProcess -FilePath (Get-Process -Id $PID).Path -ArgumentList @(
    '-NoProfile', '-File', $installedManager, '-Action', 'ValidateTaskBoard', '-SourceRoot', $unpacked
  ) -Environment @{ PATH = $minimalPath }
  if ($persistentVerify.Exit -ne 0) { throw "Persistent manager lacks trusted verifier: $($persistentVerify.Error)" }

  $stableResult = Invoke-TestProcess -FilePath (Get-Process -Id $PID).Path -ArgumentList @(
    '-NoProfile', '-File', $manager, '-Action', 'MarkStable',
    '-CodexHome', $codex, '-AgentsHome', $agents
  )
  if ($stableResult.Exit -ne 0) { throw "MarkStable failed: $($stableResult.Error)" }
  $stable = $stableResult.Out | ConvertFrom-Json

  # Scenario: downgrade the fake homes to a genuine legacy package without board source/payload.
  # Expected: receipt-owned new runtime disappears wholly while separate project DB bytes remain.
  $legacy = Join-Path $fixture 'legacy'
  New-Item -ItemType Directory -Path "$legacy/agents", "$legacy/skills/team-core" -Force | Out-Null
  [IO.File]::WriteAllText("$legacy/VERSION", '0.1.0')
  [IO.File]::WriteAllText("$legacy/agents/team-fixture.toml", 'name = "team-fixture"')
  [IO.File]::WriteAllText("$legacy/skills/team-core/SKILL.md", "---`nname: team-core`ndescription: Legacy fixture.`n---")
  $rollback = Invoke-TestProcess -FilePath (Get-Process -Id $PID).Path -ArgumentList @(
    '-NoProfile', '-File', $manager, '-Action', 'Deploy', '-SourceRoot', $legacy,
    '-CodexHome', $codex, '-AgentsHome', $agents
  ) -Environment @{ PATH = $minimalPath }
  if ($rollback.Exit -ne 0) { throw "Legacy downgrade failed: $($rollback.Error)" }
  if (Test-Path -LiteralPath (Join-Path $agents 'skills/team-core/runtime/task-board')) {
    throw 'Legacy downgrade left generated runtime behind.'
  }
  if ((Get-FileHash -LiteralPath $database).Hash -cne $databaseHash) {
    throw 'Package downgrade changed separate project database bytes.'
  }
  # Scenario: restore the pinned new-runtime snapshot after legacy downgrade.
  # Expected: exact runtime bytes return and the separate project database remains untouched.
  $restore = Invoke-TestProcess -FilePath (Get-Process -Id $PID).Path -ArgumentList @(
    '-NoProfile', '-File', $manager, '-Action', 'Restore', '-SnapshotId', $stable.snapshotId,
    '-CodexHome', $codex, '-AgentsHome', $agents
  ) -Environment @{ PATH = $minimalPath }
  if ($restore.Exit -ne 0) { throw "Snapshot restore failed: $($restore.Error)" }
  if ((Get-TestFingerprint (Join-Path $agents 'skills/team-core/runtime/task-board')) -cne
      (Get-TestFingerprint (Join-Path $unpacked $runtimeRelative))) { throw 'Snapshot restore bytes differ from selected payload.' }
  if ((Get-FileHash -LiteralPath $database).Hash -cne $databaseHash) {
    throw 'Snapshot restore changed separate project database bytes.'
  }
  Write-Output 'PASS P4.exactRefAutocrlfNoBuild and P4.legacyRollbackDatabasePreserved and P4.snapshotRestore'
} finally {
  # Only this suite's direct owned prefix is eligible for recursive cleanup.
  $resolved = [IO.Path]::GetFullPath($fixture)
  $expectedParent = [IO.Path]::GetFullPath($fixtureParent)
  if ([IO.Path]::GetDirectoryName($resolved) -cne $expectedParent -or
      [IO.Path]::GetFileName($resolved) -cnotmatch '^p4-package-[a-f0-9]{32}$') {
    throw "Refusing unsafe fixture cleanup: $resolved"
  }
  if (Test-Path -LiteralPath $resolved) { Remove-Item -LiteralPath $resolved -Recurse -Force }
}
