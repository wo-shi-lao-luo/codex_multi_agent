/** Build only the committed task-board payload; never install dependencies or run package hooks. */
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';

const runtime = 'skills/team-core/runtime/task-board';
const source = 'packages/task-board';
const wrapper = '// Generated by build-task-board; do not edit.\nimport \'./src/cli/cli.mjs\';\n';
const licenses = ['LICENSE', 'LICENCE', 'COPYING'].flatMap(name =>
  [name, `${name}.txt`, `${name}.md`]);
const fail = message => { throw new Error(`TASK_BOARD: ${message}`); };
const digest = bytes => createHash('sha256').update(bytes).digest('hex');

/** Reject linked ancestors even when the final child does not yet exist. */
function plain(target) {
  for (let current = path.resolve(target);; current = path.dirname(current)) {
    if (fs.existsSync(current) && fs.lstatSync(current).isSymbolicLink()) fail('Linked path.');
    if (path.dirname(current) === current) break;
  }
}

/** Enumerate exact portable files without following links or case-colliding names. */
function inventory(root) {
  plain(root);
  const files = [];
  const seen = new Set();
  function walk(directory) {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const full = path.join(directory, entry.name);
      const relative = path.relative(root, full).split(path.sep).join('/');
      if (!/^[A-Za-z0-9_.\/-]+$/.test(relative) ||
          relative.split('/').some(part => part === '.' || part === '..' || part.endsWith('.')) ||
          seen.has(relative.toLowerCase())) fail('Unsafe or case-colliding path.');
      seen.add(relative.toLowerCase());
      if (entry.isSymbolicLink()) fail('Linked file.');
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile()) files.push(relative);
      else fail('Unsupported file type.');
    }
  }
  walk(root);
  return files.sort();
}

/** Hash actual bytes; controlled text must already have stable LF checkout bytes. */
function read(root, relative) {
  const full = path.join(root, relative);
  plain(full);
  const bytes = fs.readFileSync(full);
  if (!bytes.includes(0) && bytes.includes(Buffer.from('\r\n'))) {
    fail(`CRLF input requires LF normalization: ${relative}`);
  }
  return bytes;
}

/** Produce expected bytes in memory first, so --check is strictly read-only. */
function build(root, check) {
  plain(root);
  const packageFiles = inventory(path.join(root, source));
  if (!packageFiles.includes('package.json') || !packageFiles.includes('src/cli/cli.mjs') ||
      !packageFiles.some(file => file.startsWith('web/'))) fail('Incomplete source package.');
  if (packageFiles.some(file => file !== 'package.json' &&
      !file.startsWith('src/') && !file.startsWith('web/'))) fail('Unexpected source package file.');
  const pkg = JSON.parse(read(root, `${source}/package.json`));
  if (['dependencies', 'devDependencies', 'optionalDependencies', 'peerDependencies']
    .some(key => Object.keys(pkg[key] ?? {}).length)) fail('Only standard-library dependencies allowed.');
  const existingLicenses = licenses.filter(file => fs.existsSync(path.join(root, file)));
  const inputPaths = ['.gitattributes', 'VERSION', 'scripts/build-task-board.mjs',
    ...packageFiles.map(file => `${source}/${file}`), ...existingLicenses].sort();
  const inputs = inputPaths.map(file => ({ path: file, sha256: digest(read(root, file)) }));
  const outputs = new Map([['cli.mjs', Buffer.from(wrapper)]]);
  for (const file of packageFiles) outputs.set(file, read(root, `${source}/${file}`));
  for (const file of existingLicenses) outputs.set(file, read(root, file));
  const manifest = {
    schemaVersion: 1,
    inputs,
    outputs: [...outputs.keys()].sort().map(file => ({ path: file, sha256: digest(outputs.get(file)) })),
    buildTool: { name: 'build-task-board', version: 1 },
    requiredNode: '>=26.13.0 <27', minimumSQLite: '3.54.0',
    dependencyLock: 'none;standard-library-only',
    licenseStatus: existingLicenses.length ? 'present-unreviewed' : 'not-declared',
    platformValidation: { observed: ['win32-x64'], otherPlatforms: 'unverified' },
  };
  outputs.set('manifest.json', Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`));
  const target = path.join(root, runtime);
  plain(target);
  const actual = fs.existsSync(target) ? inventory(target) : [];
  const expected = [...outputs.keys()].sort();
  if (check) {
    if (JSON.stringify(actual) !== JSON.stringify(expected) ||
        expected.some(file => !fs.readFileSync(path.join(target, file)).equals(outputs.get(file)))) {
      fail('Generated payload differs; rebuild from frozen sources.');
    }
    return;
  }
  // Refuse unknown output rather than recursively deleting a potentially owned directory.
  if (actual.some(file => !outputs.has(file))) fail('Unexpected output; inspect before rebuilding.');
  for (const [file, bytes] of outputs) {
    const destination = path.join(target, file);
    plain(destination);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, bytes);
  }
}

try {
  let root;
  let check = false;
  const args = process.argv.slice(2);
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--check') check = true;
    else if (args[i] === '--project-root' && args[i + 1]) root = path.resolve(args[++i]);
    else fail('Usage: --project-root ROOT [--check]');
  }
  if (!root) fail('--project-root is required.');
  build(root, check);
  console.log(`Task-board payload ${check ? 'verified' : 'built'}.`);
} catch (error) {
  console.error(error.message.startsWith('TASK_BOARD:') ? error.message : `TASK_BOARD: ${error.message}`);
  process.exitCode = 1;
}
